export const DEPARTMENT_TEXT: Localized<Record<DepartmentId, DepartmentText>> = {
  th,
  en,
  'zh-CN': zhCN,
};

export function departmentsFor(locale: Locale): DepartmentInfo[] {
  return META.map((m) => ({ ...m, ...DEPARTMENT_TEXT[locale][m.id] }));
}

const BY_LOCALE: Record<Locale, DepartmentInfo[]> = {
  th: departmentsFor('th'),
  en: departmentsFor('en'),
  'zh-CN': departmentsFor('zh-CN'),
};

export function getDepartment(id: DepartmentId, locale: Locale = 'th'): DepartmentInfo {
  const found = BY_LOCALE[locale].find((d) => d.id === id);
  if (!found) throw new Error(`Unknown department: ${id}`);
  return found;
}

/** All departments in the current public locale. */
export function useDepartments(): DepartmentInfo[] {
  return BY_LOCALE[useLocale().locale];
}

/** One department in the current public locale. */
export function useDepartment(id: DepartmentId): DepartmentInfo {
  return getDepartment(id, useLocale().locale);
}

/** Thai-locale list, kept for code that has no locale (tests, static checks). */
export const DEPARTMENTS: readonly DepartmentInfo[] = BY_LOCALE.th;


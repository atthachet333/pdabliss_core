export type DepartmentId =
  'sales' | 'warehouse' | 'purchasing' | 'operations' | 'accounting' | 'reports' | 'executive';

interface DepartmentText {
  /** Name in the current locale. */
  name: string;
  /** One-line purpose shown on cards. */
  purpose: string;
  /** What the department's workspace focuses on. */
  focus: readonly string[];
  /** Documents the department owns or touches. */
  documents: readonly string[];
  /** How data visibility is scoped for this department. */
  visibility: string;
  /** Short module list for the CORE World detail card. */
  highlights: readonly string[];
}

export interface DepartmentInfo extends DepartmentText {
  id: DepartmentId;
  /** English name — the secondary label beside the localized name. */
  nameEn: string;
  icon: LucideIcon;
  /** Department scene (public/departments, generated by `npm run assets`). */
  image: { sm: string; lg: string };
  /** Workspace route, when the department has its own workspace. */
  workspace?: string;
}


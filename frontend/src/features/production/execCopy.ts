/** Execution copy and an error text that knows both the execution and the planning codes. */
export function useExec() {
  const x = useCopy(EXEC_COPY);
  const c = useCopy(PRODUCTION_COPY);
  const cc = useCopy(CONTROL_COPY);
  const err = (e: unknown) => {
    if (e instanceof ApiError) {
      if (e.code === 'MI_NOT_FOUND' || e.code === 'MO_NOT_FOUND') return c.notFound;
      if (x.errors[e.code]) return x.errors[e.code]!;
      if (c.errors[e.code]) return c.errors[e.code]!;
    }
    return errorText(e, cc);
  };
  return { x, c, err };
}

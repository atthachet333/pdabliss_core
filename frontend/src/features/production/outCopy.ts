/** Output copy and an error text that knows the output, execution-free planning codes too. */
export function useOut() {
  const o = useCopy(OUT_COPY);
  const c = useCopy(PRODUCTION_COPY);
  const cc = useCopy(CONTROL_COPY);
  const err = (e: unknown) => {
    if (e instanceof ApiError) {
      if (o.errors[e.code]) return o.errors[e.code]!;
      if (e.code === 'MO_NOT_FOUND') return c.notFound;
      if (c.errors[e.code]) return c.errors[e.code]!;
    }
    return errorText(e, cc);
  };
  return { o, c, err };
}

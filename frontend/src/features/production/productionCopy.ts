export function productionError(e: unknown, c: ProductionCopy, control: ControlCopy) {
  if (e instanceof ApiError) {
    if (e.code === 'MO_NOT_FOUND' || e.code === 'BOM_NOT_FOUND') return c.notFound;
    if (c.errors[e.code]) return c.errors[e.code]!;
  }
  return errorText(e, control);
}

/** Production copy in the current language, and its error text. */
export function useProd() {
  const c = useCopy(PRODUCTION_COPY);
  const cc = useCopy(CONTROL_COPY);
  return { c, err: (e: unknown) => productionError(e, c, cc) };
}

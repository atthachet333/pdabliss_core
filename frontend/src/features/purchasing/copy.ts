/**
 * A user-facing message for an API error: purchase-request codes here, the
 * common ones (permission, branch, validation, generic) from the Control
 * Center copy already loaded with CORE.
 */
export function prError(e: unknown, c: PrCopy, control: ControlCopy) {
  if (e instanceof ApiError && c.errors[e.code]) return c.errors[e.code]!;
  return errorText(e, control);
}

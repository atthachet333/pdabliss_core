export const ORDER_COPY: Localized<OrderCopy> = { th, en, 'zh-CN': zh };

export function poError(e: unknown, c: OrderCopy, control: ControlCopy) {
  if (e instanceof ApiError && c.errors[e.code]) return c.errors[e.code]!;
  return errorText(e, control);
}

/**
 * Formats a server decimal string as money in the current language — the
 * string goes to Intl as is (no float conversion), always 2 decimals.
 */
export function useMoney() {
  const { locale } = useLocale();
  const fmt = new Intl.NumberFormat(
    locale === 'zh-CN' ? 'zh-CN' : locale === 'th' ? 'th-TH' : 'en',
    {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    },
  );
  return (value: string | null, currency?: string) =>
    value === null
      ? '—'
      : `${fmt.format(value as unknown as number)}${currency ? ` ${currency}` : ''}`;
}

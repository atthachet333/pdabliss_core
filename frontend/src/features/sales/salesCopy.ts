export function salesError(e: unknown, c: SalesCopy, control: ControlCopy) {
  if (e instanceof ApiError) {
    if (e.code === 'SO_NOT_FOUND') return c.notFound;
    if (c.errors[e.code]) return c.errors[e.code]!;
  }
  return errorText(e, control);
}

/** Exact decimal strings → grouped money text (Intl formats the string, no float rounding). */
export function useMoney() {
  const { locale } = useLocale();
  const lang = locale === 'th' ? 'th-TH' : locale;
  const amount = new Intl.NumberFormat(lang, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  // Unit prices carry up to four places — shown exactly, never rounded for display.
  const price = new Intl.NumberFormat(lang, { minimumFractionDigits: 2, maximumFractionDigits: 4 });
  return (value: string, currency?: string, exact = false) =>
    `${(exact ? price : amount).format(value as unknown as number)}${currency ? ` ${currency}` : ''}`;
}

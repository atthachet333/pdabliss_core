/** EP32 codes first, then the EP31 Warehouse codes (lots, precision …), then the shared ones. */
export function ctlError(e: unknown, k: CtlCopy, c: WhCopy, control: ControlCopy) {
  if (e instanceof ApiError) {
    if (k.errors[e.code]) return k.errors[e.code]!;
    if (e.code.endsWith('_NOT_FOUND') && /^(TRANSFER|ADJUSTMENT|COUNT)/.test(e.code))
      return k.notFound;
  }
  return whError(e, c, control);
}

/** "TRANSFER_POSTED" → "Posted" (by its last word). */
export const timelineLabel = (k: CtlCopy, type: string) =>
  k.timeline[type.slice(type.lastIndexOf('_') + 1)] ?? type;
